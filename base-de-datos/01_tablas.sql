-- =====================================================================
-- HARVEST JAM · Sistema de gestión para fruterías
-- 01_tablas.sql — Esquema y tablas (PostgreSQL 13 o superior)
--
-- Orden: 01_tablas → 02_funciones → 03_triggers → 04_roles → 05_datos
-- (→ 06_datos_simulados, opcional). Ejecutar como postgres, conectado a la
-- base de datos del sistema (por defecto "TBD"), sobre una base vacía o
-- después de 99_borrar_todo.sql.
--
-- Se conservan los nombres de tablas y columnas del proyecto original.
-- Cambios respecto a Tablas.sql (ver docs/CAMBIOS_BD.md):
--   * Las llaves primarias generan su valor solas (identity). Antes los
--     INSERT sin id fallaban y no se podía registrar nada nuevo.
--   * Cantidades y existencias aceptan decimales (1.5 kg).
--   * Los detalles guardan el precio al momento de la venta o compra,
--     para que los totales históricos no cambien al subir un precio.
--   * venta.fecha y compra.fecha guardan también la hora (ticket).
--   * empleado.usuario liga a cada empleado con su usuario de PostgreSQL.
--   * Restricciones NOT NULL, CHECK y llaves primarias que faltaban.
-- =====================================================================

create schema if not exists fruteria authorization postgres;

set search_path to fruteria, public;

-- Que todas las conexiones a esta base usen el esquema fruteria.
do $$
begin
    execute format('alter database %I set search_path = fruteria, public', current_database());
end
$$;

-- ---------------------------------------------------------------------
-- Tablas independientes
-- ---------------------------------------------------------------------

create table producto (
    codigo         integer generated by default as identity (start with 5100) primary key,
    descripcion    varchar(100)  not null,
    categoria      varchar(50)   not null default 'fruta',
    unidad_medida  varchar(20)   not null default 'kilogramo',
    existencia     numeric(10,3) not null default 0 check (existencia >= 0),
    precio_c       numeric(8,2)  not null default 0 check (precio_c >= 0),
    precio_v       numeric(8,2)  not null check (precio_v > 0),
    stock_minimo   numeric(10,3) check (stock_minimo >= 0),
    vida_util_dias integer       check (vida_util_dias between 1 and 60)
);

create table proveedor (
    id_p integer generated by default as identity (
        start
        with
            2100
    ) primary key,
    nombre varchar(100) not null,
    ciudad varchar(50) not null,
    contacto varchar(100),
    tel_contacto varchar(20)
);

create table cliente (
    id_c integer generated by default as identity (
        start
        with
            3200
    ) primary key,
    telefono varchar(15),
    rfc varchar(16),
    domicilio varchar(200)
);

create table empleado (
    id_e integer generated by default as identity (
        start
        with
            7100
    ) primary key,
    nombre varchar(80) not null,
    turno varchar(20) not null default 'matutino' check (
        turno in (
            'matutino',
            'vespertino',
            'nocturno'
        )
    ),
    salario numeric(14, 2) not null check (salario > 0),
    usuario varchar(63) unique -- usuario de PostgreSQL con el que inicia sesión
);

create table auditoria (
    id integer generated by default as identity primary key,
    fecha_hora timestamp(0) not null default localtimestamp(0),
    tabla varchar(50) not null,
    operacion varchar(10) not null check (
        operacion in ('INSERT', 'UPDATE', 'DELETE')
    ),
    usuario varchar(80) not null default session_user,
    descripcion text
);

-- ---------------------------------------------------------------------
-- Tablas con llaves foráneas
-- ---------------------------------------------------------------------

create table producto_proveedor (
    codigo integer not null references producto (codigo) on delete cascade,
    id_p integer not null references proveedor (id_p) on delete cascade,
    dias_entrega integer check (dias_entrega between 0 and 30),
    primary key (codigo, id_p)
);

create table p_moral (
    id_c integer primary key references cliente (id_c) on delete cascade,
    razon_social varchar(100) not null
);

create table p_fisica (
    id_c integer primary key references cliente (id_c) on delete cascade,
    nombre varchar(80) not null
);

create table supervisor (
    id_e integer primary key references empleado (id_e) on delete cascade,
    id_s integer not null references empleado (id_e) on delete cascade,
    check (id_e <> id_s)
);

create table venta (
    folio_v integer generated by default as identity (
        start
        with
            100
    ) primary key,
    fecha timestamp(0) not null default localtimestamp(0),
    id_c integer references cliente (id_c),
    id_e integer references empleado (id_e)
);

create table compra (
    folio_c integer generated by default as identity (
        start
        with
            9000
    ) primary key,
    no_lote integer,
    fecha timestamp(0) not null default localtimestamp(0),
    id_p integer not null references proveedor (id_p),
    id_e integer references empleado (id_e)
);

create table detalle_venta (
    codigo integer not null references producto (codigo) on delete restrict,
    folio_v integer not null references venta (folio_v) on delete cascade,
    observaciones varchar(50),
    cantidad numeric(10, 3) not null check (cantidad > 0),
    precio_unitario numeric(8, 2) check (precio_unitario >= 0),
    primary key (folio_v, codigo)
);

create table detalle_compra (
    folio_c integer not null references compra (folio_c) on delete cascade,
    codigo integer not null references producto (codigo) on delete restrict,
    cantidad numeric(10, 3) not null check (cantidad > 0),
    precio_unitario numeric(8, 2) check (precio_unitario >= 0),
    primary key (folio_c, codigo)
);

-- ---------------------------------------------------------------------
-- Índices para las consultas del sistema
-- ---------------------------------------------------------------------

create index idx_venta_fecha on venta (fecha);

create index idx_venta_cliente on venta (id_c);

create index idx_venta_empleado on venta (id_e);

create index idx_compra_fecha on compra (fecha);

create index idx_compra_proveedor on compra (id_p);

create index idx_detalle_venta_codigo on detalle_venta (codigo);

create index idx_detalle_compra_codigo on detalle_compra (codigo);

create index idx_auditoria_fecha on auditoria (fecha_hora desc);

create index idx_auditoria_tabla on auditoria (tabla);

select 'esquema fruteria creado' as estado;